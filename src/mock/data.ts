const buildReputation = (creditScore: number, totalTrades: number): Reputation => ({
  totalDeals: totalTrades,
  pigeonRate: Math.max(0, 0.05 - (creditScore - 900) * 0.0005),
  wrongShipRate: Math.max(0, 0.03 - (creditScore - 900) * 0.0003),
  positiveRate: Math.min(0.99, 0.85 + (creditScore - 800) * 0.0014),
  starRating: Math.round((creditScore / 200) * 10) / 10,
  quickTags: creditScore >= 980
    ? ['金牌商家', '发货快', '货靠谱', '价格公道']
    : creditScore >= 950
    ? ['诚信认证', '发货快', '服务好']
    : creditScore >= 900
    ? ['诚信认证', '服务好']
    : ['新入驻'],
});

const buildCertificationBadges = (creditScore: number): string[] => {
  const badges: string[] = [];
  if (creditScore >= 950) badges.push('金牌商家');
  if (creditScore >= 900) badges.push('诚信认证');
  if (creditScore >= 850) badges.push('实名认证');
  return badges;
};

const extractCity = (address: string): string => {
  const match = address.match(/^(.*?市)/);
  return match ? match[1] : address.slice(0, 6);
};

